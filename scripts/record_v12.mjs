// Scripted 90-second walkthrough using actual local APIs. No mocked routes.
import { chromium } from "../frontend/node_modules/@playwright/test/index.mjs";
import { mkdir, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";

await mkdir("docs/demo/v1.2", { recursive: true });
await mkdir("work/v12-recordings", { recursive: true });
const browser = await chromium.launch();
const context = await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:"work/v12-recordings",size:{width:1440,height:1000}}});
const page=await context.newPage();
const calls=[]; const actions=[]; let start=Date.now();
page.on("response",async response=>{if(response.url().endsWith("/api/research")){calls.push(await response.json());}});
const mark=name=>actions.push({at_seconds:(Date.now()-start)/1000,action:name});
const until=async seconds=>{const remaining=seconds*1000-(Date.now()-start);if(remaining>0)await page.waitForTimeout(remaining);};
try {
  await page.goto("http://127.0.0.1:8000/");
  await page.locator(".metric strong").first().filter({hasText:"391,035"}).waitFor();
  start=Date.now();mark("Actual local workspace");
  await until(5);
  await page.getByLabel("Research question",{exact:true}).fill("Compare Apple operating margin in 2023 and 2024. Show percentage point change.");
  const financial=page.waitForResponse(r=>r.url().endsWith("/api/research")&&r.request().method()==="POST");
  await page.getByRole("button",{name:"Research question",exact:true}).click();
  const f=await(await financial).json();
  if(f.status!=="answered"||f.origin!=="deterministic finance engine")throw new Error("Verified calculation failed");
  const data=page.getByRole("region",{name:"Verified financial data"});
  await data.scrollIntoViewIfNeeded();mark("Verified result without model approval");
  await until(12);await data.getByText("Formula and verified inputs").first().click();
  await until(19);await data.locator(".citations button").first().click();
  await page.getByRole("link",{name:"Open official filing"}).waitFor();mark("Original evidence, dates and source identifier");
  await page.screenshot({path:"docs/demo/v1.2/financial-evidence.png",fullPage:true});
  await until(26);
  await page.getByRole("button",{name:"Financials & Valuation",exact:true}).click();
  const ev=page.getByTestId("enterprise-value");await ev.scrollIntoViewIfNeeded();const before=await ev.innerText();
  await page.getByLabel("Discount rate",{exact:true}).fill("12");
  await page.waitForFunction(old=>document.querySelector('[data-testid="enterprise-value"]').innerText!==old,before);
  mark("Changed discount-rate assumption; same server finance engine");
  await until(34);
  const downloaded=page.waitForEvent("download");await page.getByRole("button",{name:"Export this scenario to PDF"}).click();
  await(await downloaded).saveAs("work/v12-demo-scenario.pdf");mark("Actual PDF exported");
  await page.screenshot({path:"docs/demo/v1.2/valuation.png",fullPage:true});
  await until(40);
  await page.getByRole("button",{name:"Research",exact:true}).click();
  await page.getByLabel("Covered company",{exact:true}).selectOption("DELL");
  await page.getByLabel("Research question",{exact:true}).fill("How can acquisition debt covenants constrain Dell capital raising and operating flexibility in 2023?");
  const generated=page.waitForResponse(r=>r.url().endsWith("/api/research")&&r.request().method()==="POST");
  await page.getByRole("button",{name:"Research question",exact:true}).click();mark("Actual local explanation request; development walkthrough question");
  const g=await(await generated).json();
  if(g.status!=="answered"||!g.model)throw new Error("Actual local generated explanation unavailable");
  await page.locator(".answer-card .claim").first().scrollIntoViewIfNeeded();mark("AI claims separately labeled with evidence");
  await page.locator(".answer-card .claim .citations button").first().click();
  await page.getByRole("link",{name:"Open official filing"}).waitFor();
  await page.screenshot({path:"docs/demo/v1.2/generated-evidence.png",fullPage:true});
  await until(76);
  await page.getByRole("button",{name:"Sources & Evaluation",exact:true}).click();
  await page.getByRole("heading",{name:"Official source register"}).waitFor();
  await page.evaluate(()=>window.scrollTo(0,0));mark("Source register, evaluation and pending human review");
  if(Date.now()-start>88500)throw new Error("Walkthrough exceeded 90-second recording budget; raw take retained");
  await until(90.4);
  const video=page.video();await context.close();await video.saveAs("work/ResearchDesk-v1.2-raw.webm");
  await writeFile("docs/demo/v1.2/recording.json",JSON.stringify({recorded_at:new Date().toISOString(),commit:execFileSync("git",["rev-parse","HEAD"],{encoding:"utf8"}).trim(),actions,actual_calls:calls.map(r=>({status:r.status,origin:r.origin,model:r.model,answer:r.answer,elapsed_seconds:r.elapsed_seconds})),note:"Actual local Chromium walkthrough. No mocked routes, cached answers or authored model output. Scripted development question, not an independent evaluation. Reading pauses are intentional. Final WebM trims only the idle tail to 90 seconds; PDF was actually downloaded after changing WACC to 12%."},null,2)+"\n");
} finally {await browser.close();}
